function hourWord(h) {
  h = ((h % 24) + 24) % 24;
  const hh = Math.floor(h);
  const h12 = hh % 12 === 0 ? 12 : hh % 12;
  const part = hh < 5 ? 'রাত' : hh < 12 ? 'সকাল' : hh < 15 ? 'দুপুর' : hh < 18 ? 'বিকেল' : hh < 20 ? 'সন্ধ্যা' : 'রাত';
  return `${part} ${bn(h12)}টা`;
}

