const EXTRAS = [sPoll, sLetters, sStocks, sTv, sObit, sSports, sMarket, sWeather, sCorrections, sCartoon, sQuiz];

function weatherStrip(G, s, F) {
  const h = s.deathHour ?? 16;
  const night = h >= 19 || h < 5;
  const a = [];
  a.push(night ? '🌙 রাতের সংস্করণ' : h < 12 ? '🌅 সকালের সংস্করণ' : '☀️ বিকেলের সংস্করণ');
  a.push(F.flood ? '🌊 রাস্তায় হাঁটুপানি' : F.rain ? '🌧️ থেমে থেমে বৃষ্টি' : pick(['🧅 পেঁয়াজ সূচক: ৳৩০০ ▲', '😷 ধুলা: বিপজ্জনক (স্বাভাবিক)']));
  a.push(F.shed ? '🕯️ বিদ্যুৎ: আসা-যাওয়ায়' : pick(['🚌 বাস থামার সম্ভাবনা: ২%', '🚦 সিগন্যাল মানার হার: ৩%']));
  return a;
}

function dropcap(text) {
  const m = text.match(/^.[\u0981-\u0983\u09BC-\u09D7\u09E2\u09E3]*/u);
  const first = m ? m[0] : text[0];
  return `<span class="dropcap">${first}</span>${text.slice(first.length)}`;
}

